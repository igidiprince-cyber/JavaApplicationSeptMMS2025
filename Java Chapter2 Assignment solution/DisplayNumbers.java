// Display Numbers 1 to 4

public class DisplayNumbers {
    public static void main(String[] args) {

        // a
        System.out.println("1 2 3 4");

        // b
        System.out.print("1 ");
        System.out.print("2 ");
        System.out.print("3 ");
        System.out.print("4\n");

        // c
        System.out.printf("1 2 3 4%n");
    }
}